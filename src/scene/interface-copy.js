const copy=()=>interfaceCopy[config.language];
function applyLocale(){
  const text=copy();root.lang=config.language==='zh'?'zh-CN':'en';root.setAttribute('aria-label',text.sceneLabel);
  qa('[data-dc-text]').forEach(el=>el.textContent=el.dataset.dcText==='identity'&&config.identity?config.identity:text[el.dataset.dcText]);
  qa('[data-dc-aria]').forEach(el=>el.setAttribute('aria-label',text[el.dataset.dcAria]));
  qa('[data-dc-alt]').forEach(el=>el.alt=text[el.dataset.dcAlt]);
  qa('.dc-check').forEach((row,i)=>row.querySelector('.dc-check-name').textContent=text.checks[i]);
  refreshPhaseCopy();refreshAccessCopy();updateSound();updateHomeCopy();
  if(state.speechStatus)updateSpeechStatus(state.speechStatus);
}
function refreshPhaseCopy(){
  const text=copy(),index=Math.max(0,state.lastPhase),stage=stages[index];
  q('.dc-phase-title').textContent=text.stageTitles[index];q('.dc-boot-detail').textContent=text.stageDetails[index];q('.dc-phase-code').textContent=text.stageCodes[index];
  qa('.dc-check').forEach((row,i)=>{row.classList.toggle('done',i<stage.checked);row.querySelector('.dc-check-status').textContent=i<stage.checked?text.checkReady:i===stage.checked?text.checkStarting:text.checkIdle;});
}
function refreshAccessCopy(){
  const text=copy(),verifying=state.mode==='verifying',step=Math.max(0,state.linkStep);
  const permitting=state.mode==='permitting',permissionDone=q('.dc-permission').classList.contains('dc-gate-confirmed');
  const permissionStatus=permissionDone?text.permissionConfirmed:permitting?text.permissionPending:text.permit;
  q('.dc-permit .dc-entry-label').textContent=permissionStatus;
  q('.dc-permit').setAttribute('aria-label',text.confirmPermission);
  q('.dc-permission .dc-gate-status').textContent=permitting?permissionStatus:'';
  q('.dc-confirm .dc-entry-label').textContent=verifying?text.verifySteps[step]:text.confirm;
  q('.dc-confirm').setAttribute('aria-label',text.confirmIdentity);
  q('.dc-login .dc-gate-status').textContent=verifying?text.verifySteps[step]:'';
  q('.dc-enter').setAttribute('aria-label',text.enterMain);
}
function updateSpeechStatus(status){
  state.speechStatus=status;
  root.dataset.voiceState=status.state;root.dataset.voiceCue=status.text||'';root.dataset.voiceName=status.voiceName||'';
  root.classList.toggle('dc-speaking',status.state==='speaking');
}
